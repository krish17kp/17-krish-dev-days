/*
 * Publisher data access helpers.
 * These queries return the curated publisher list used by Astro pages during static builds.
 */
import { asc } from 'drizzle-orm';
import type { Database } from './db';
import { publishers } from '../../db/schema';
import type { Publisher } from '../types/game';

/**
 * Retrieves every publisher from the database in alphabetical order.
 *
 * @param db - The database instance used to query publishers.
 * @returns A list of publishers with their ids and names sorted by name.
 */
export async function getAllPublishers(db: Database): Promise<Publisher[]> {
    const rows = await db
        .select({ id: publishers.id, name: publishers.name })
        .from(publishers)
        .orderBy(asc(publishers.name));

    return rows.map((row) => ({
        id: row.id,
        name: row.name,
    }));
}
